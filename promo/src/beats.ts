export const BEATS: number[] = [
  0.104, 0.325, 0.58, 0.848, 1.068, 1.289, 1.997, 2.67, 3.576, 3.808, 4.063,
  4.319, 4.586, 4.876, 5.782, 6.641, 7.14, 7.372, 7.663, 7.895, 8.115, 8.371,
  9.137, 9.601, 9.822, 10.437, 10.704, 10.925, 11.146, 11.389, 11.61, 11.831,
  12.237, 12.945, 13.224, 14.106, 14.431, 14.652, 14.872, 15.105, 15.325,
  15.581, 16.3, 16.974, 17.903, 18.135, 18.39, 18.611, 18.843, 20.108, 20.852,
  21.142, 21.455, 21.699, 21.989, 22.221, 22.442, 22.698, 23.464, 24.137,
  25.066, 25.391, 25.646, 26.006, 26.331, 26.831,
];

export const beatPulse = (t: number, decay = 7): number => {
  let p = 0;
  for (const b of BEATS) {
    const dt = t - b;
    if (dt >= 0 && dt < 0.6) p = Math.max(p, Math.exp(-dt * decay));
  }
  return p;
};